function getCharPattern(char: string): string[] {
  const upper = char.toUpperCase()
  return FONT[upper] ?? FONT["?"] ?? FONT[" "]
}

/**
 * Converts text to ASCII block art.
 * @param text - Input text (typically a title)
 * @param maxChars - Maximum characters to render (default 8)
 * @returns Array of strings, each a row of the ASCII art
 */
export function textToAsciiArt(text: string, maxChars = 8): string[] {
  const cleaned = (text || "")
    .trim()
    .replace(/\s+/g, " ")
    .slice(0, maxChars)
  if (!cleaned) return []

  const rows: string[] = ["", "", "", "", ""]
  for (let i = 0; i < cleaned.length; i++) {
    const pattern = getCharPattern(cleaned[i])
    for (let r = 0; r < 5; r++) {
      rows[r] += pattern[r].replace(/1/g, BLOCK).replace(/0/g, SPACE)
      if (i < cleaned.length - 1) rows[r] += SPACE // letter spacing
    }
  }
  return rows
}
